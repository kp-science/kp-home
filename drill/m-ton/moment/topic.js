function toolFig(o){
  const h=o.h||176, yb=86, th=11, x0=FX0, x1=FX1, L=o.L, sc=(x1-x0)/L, X=p=>x0+p*sc;
  let s='';
  (o.dims||[]).forEach(d=>{ s+=G.dim(X(d[0]),X(d[1]),d[3]!==undefined?d[3]:yb-28,d[2]); });
  s+=G.beam(x0,yb,x1-x0,th);

  /* ชิ้นส่วนเฉพาะของเครื่องมือ ให้รู้ว่ากำลังพูดถึงอะไรในชีวิตจริง */
  if(o.kind==='barrow'){
    s+='<circle cx="'+X(o.pivot)+'" cy="'+(yb+th+14)+'" r="14" class="fful"/>'+
       '<circle cx="'+X(o.pivot)+'" cy="'+(yb+th+14)+'" r="4" class="fdot"/>'+
       '<line x1="'+X(o.pivot)+'" y1="'+(yb+th)+'" x2="'+X(o.pivot)+'" y2="'+(yb+th+14)+'" class="fkl"/>'+
       G.t(X(o.pivot),yb+th+42,'ล้อ = จุดหมุน',9,'fts');
  } else if(o.kind==='hammer'){
    s+='<path d="M'+(X(o.pivot)-16)+','+(yb+th)+' q16,22 32,0 z" class="fful"/>'+
       '<line x1="'+X(o.load)+'" y1="'+(yb+th)+'" x2="'+X(o.load)+'" y2="'+(yb+th+20)+'" class="fkl2"/>'+
       G.t(X(o.load),yb+th+34,'ตะปู',9,'fts')+
       G.t(X(o.pivot),yb+th+34,'จุดหมุน',9,'fts');
  } else {   /* tong — ที่คีบ บานพับอยู่ปลายข้างหนึ่ง */
    s+='<circle cx="'+X(o.pivot)+'" cy="'+(yb+th/2)+'" r="5" class="fdot"/>'+
       G.t(X(o.pivot),yb+th+26,'บานพับ',9,'fts')+
       '<path d="M'+(X(o.load)-4)+','+(yb+th)+' l8,0 l-4,13 z" class="fbeam"/>';
  }

  (o.items||[]).forEach(it=>{ const x=X(it[0]);
    if(it[1]==='down') s+=G.force(x,yb+th,yb+th+34,it[2]);   // แรงกดลง วาดใต้คาน
    else if(it[1]==='up') s+=G.force(x,yb,yb-34,it[2]);       // แรงยกขึ้น วาดเหนือคาน
    else if(it[1]==='hang') s+=G.hang(x,yb+th,it[2]);
    else if(it[1]==='dot') s+=G.dot(x,yb+th/2,it[2]);
  });
  if(o.note) s+=G.t(FW/2,h-8,o.note,9.4,'fts');
  return G.svg(FW,h,s);
}

